    /// <summary>
    /// ????????????
    /// </summary>
    void HandleMovement()
    {
        // ??????????????????????
        if (_moveInput != Vector2.zero)
        {
            // ===== ????1: ????????????? =====

            // ??2D????????3D????????
            Vector3 inputDirection = new Vector3(_moveInput.x, 0.0f, _moveInput.y).normalized;

            // ???????????????????????
            float inputAngle = Mathf.Atan2(inputDirection.x, inputDirection.z) * Mathf.Rad2Deg;
            //Mathf.Atan2(y, x) ???????????????????????????????????????X??????

            // ???????????Y?????????????????????????  //?????mainCamera????cinemachine????????????????????????????????
            _targetRotation = inputAngle + mainCamera.transform.eulerAngles.y;

            // ===== ????2: ????????? =====

            // ???SmoothDampAngle?????????????
            float smoothRotation = Mathf.SmoothDampAngle(
                transform.eulerAngles.y,      // ??????//eulerAngles??????y?????????????
                _targetRotation,               // ?????
                ref _rotationVelocity,         // ??????????
                rotationSmoothTime              // ??????
            );

            // ??????//????????y?????
            transform.rotation = Quaternion.Euler(0.0f, smoothRotation, 0.0f);

            // ===== ????3: ?????????????? =====

            // ???????????????????
            Vector3 moveDirection = Quaternion.Euler(0.0f, _targetRotation, 0.0f) * Vector3.forward;

            // ??????
            float currentSpeed = moveSpeed;  // ??????????
            if (Input.GetKey(KeyCode.LeftShift) || Input.GetKey(KeyCode.RightShift))
            {
                currentSpeed = MaxSpeed;
            }
            else
            {
                currentSpeed = moveSpeed;
            }

            controller.Move(moveDirection.normalized * currentSpeed * Time.deltaTime);
        }
    }
    /// <summary>
    /// ?????????????????
    /// </summary>
    void HandleJump()
    {
        Vector3 motionVector = Vector3.zero;
        float h = ic.GetFloatInputValue(InputCode.HorizontalMoveValue);
        float v = ic.GetFloatInputValue(InputCode.VerticalMoveValue);

        // ???????????
        isGround = Physics.CheckSphere(checkpoint.position, checkSphereRadius, groundLayer);

        // ????????
        if (!isGround || isJumping)
        {
            verticalVelocity -= gravity * Time.deltaTime;

            // ?????
            if (verticalVelocity <= 0 && isJumping && isGround)
            {
                isJumping = false;
                JudgeAndChangeStateIdleOrMove(v, h);
            }
        }

        motionVector += Vector3.up * verticalVelocity * Time.deltaTime;

        // ===== ??????????????????? =====
        bool jumpPressed = ic.GetBoolInputValue(InputCode.JumpState);
        float timeSinceLastJump = Time.time - lastJumpTime;
        bool canJump = timeSinceLastJump >= jumpCooldown;

        // ?????????????????????????????????????????????
        if (jumpPressed && isGround && !isJumping && canJump)
        {
            isJumping = true;
            verticalVelocity = Mathf.Sqrt(2 * gravity * maxJumpHeight);
            characterFSM.ChangeState(CHARACTERSTATE.JUMP);

            // ?????????????
            lastJumpTime = Time.time;

        }

        controller.Move(motionVector);
    }

    /// <summary>
    /// ?????????idle????Move
    /// </summary>
    private void JudgeAndChangeStateIdleOrMove(float v, float h)
    {
        if (v != 0 || h != 0)      //  || (??)
        {
            characterFSM.ChangeState(CHARACTERSTATE.WALK);

        }
        else
        {
            characterFSM.ChangeState(CHARACTERSTATE.IDLE);
        }


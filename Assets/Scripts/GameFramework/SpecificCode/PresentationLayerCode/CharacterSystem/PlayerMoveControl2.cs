            Gizmos.color = Color.green;
            Vector3 moveDir = Quaternion.Euler(0.0f, _targetRotation, 0.0f) * Vector3.forward;
            Gizmos.DrawRay(transform.position + Vector3.up, moveDir * 2);
        }
